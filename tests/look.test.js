import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {characterBlock, mockLookSheet, JADE_LOOK, MARK_LOOK, resolveLook, normalizeLook} from '../look.js';
import {panelPrompt, panelSeed, portraitPrompt, characterSeed, migrateLibrary, validateCharacter} from '../core.js';
import {panelNegative} from '../provider.js';

const memory=new Map();
globalThis.localStorage={getItem:key=>memory.has(key)?memory.get(key):null,setItem:(key,value)=>memory.set(key,String(value)),removeItem:key=>memory.delete(key),clear:()=>memory.clear()};

const jade={id:'jade',name:'Jade',age:29,fictional:true,fixedSeed:true,personality:'wry',backstory:'a pilot',description:'',look:JADE_LOOK};
const mark={id:'mark',name:'Mark',age:34,fictional:true,fixedSeed:true,personality:'quiet',backstory:'a cook',description:'',look:MARK_LOOK};

test('a look sheet compiles to one fixed block and survives migration', ()=>{
  const block=characterBlock(jade,{scale:'all'});
  assert.equal(block, characterBlock(jade,{scale:'wide'}));
  assert.match(block, /^JADE: adult woman, long wavy honey-blonde hair with platinum highlights in a high messy bun/);
  assert.match(block, /hazel-green almond eyes/);
  assert.match(block, /warm fair skin with a golden undertone/);
  assert.match(block, /tattoos: full-color floral sleeve \(traditional, full sleeve\) on right arm from shoulder to wrist; black tiny crescent \(fine line, tiny\) on left side of the neck/);
  assert.match(block, /beauty mark just above the left side of the upper lip/);
  assert.doesNotMatch(block, /brown hair|wry|pilot/);
  const close=characterBlock(jade,{scale:'close'});
  assert.doesNotMatch(close, /floral sleeve|right arm|shoulder to wrist/);
  assert.match(close, /left side of the neck/);
  assert.match(close, /left nostril/);
  assert.match(close, /honey-blonde hair with platinum highlights/);
  assert.match(close, /hazel-green almond eyes/);
  assert.match(close, /warm fair skin/);
  const markClose=characterBlock(mark,{scale:'close'});
  assert.match(markClose, /back of the right hand/);
  assert.match(markClose, /right eyebrow/);
  assert.doesNotMatch(markClose, /wrist to elbow|forearm/);
  const legacy={name:'Mira',age:32,description:'amber eyes and a silver eyebrow piercing',hair:'dark curls in a loose bun',body:'athletic adult build',outfit:'copper flight jacket',tattoos:'CONSTELLATIONTATTOO on the left forearm'};
  const migrated=migrateLibrary({schemaVersion:1,characters:[legacy],series:[]});
  assert.equal(migrated.characters[0].description, legacy.description);
  assert.equal(migrated.characters[0].look.always, legacy.description);
  assert.equal(migrated.characters[0].look.hairColor, legacy.hair);
  assert.equal(characterBlock(resolveLook(legacy)&&legacy,{scale:'wide'}).includes('dark curls in a loose bun'), true);
  validateCharacter({...jade,description:jade.look.always});
  assert.throws(()=>validateCharacter({...jade,age:16,description:'adult woman',fictional:true}), /18/);
});

test('panel prompts copy the block verbatim, label both sides, and trim wardrobe before face', ()=>{
  const block=characterBlock(jade,{scale:'all'});
  const prompt=panelPrompt({style:'Ink',camera:'Wide establishing shot',scene:'Jade waits by the glass.',characters:[jade],limit:7500});
  assert.ok(prompt.includes(block));
  assert.match(prompt, /Use each character block verbatim/);
  assert.doesNotMatch(prompt, /wry|pilot/);
  const pair=panelPrompt({style:'Ink',camera:'Medium shot, eye level',scene:'Close on Mark while Jade waits.',characters:[jade,mark],limit:7500});
  assert.ok(pair.indexOf('MARK (on the left):')<pair.indexOf('JADE (on the right):'));
  assert.ok(pair.includes(characterBlock(mark,{scale:'mid',position:'on the left'})));
  assert.ok(pair.includes(characterBlock(jade,{scale:'mid',position:'on the right'})));
  const bulky=structuredClone(jade);
  bulky.look=normalizeLook(bulky.look);
  bulky.look.outfit=`WARDROBE ${'x'.repeat(1800)}`;
  bulky.look.tattoos=[...bulky.look.tattoos,{design:'SLEEVE',colors:'black',style:'blackwork',size:'large',placement:'left forearm, inner, wrist to elbow'}];
  const tight=panelPrompt({style:'Ink',camera:'Wide establishing shot',scene:'Jade stands.',characters:[bulky],limit:1400});
  assert.doesNotMatch(tight, /WARDROBE/);
  assert.match(tight, /honey-blonde hair with platinum highlights/);
  assert.match(tight, /hazel-green almond eyes/);
  assert.match(tight, /warm fair skin/);
  assert.match(tight, /left side of the neck/);
  const portrait=portraitPrompt(jade,'Ink',7500);
  assert.match(portrait, /head and shoulders/);
  assert.ok(portrait.includes(characterBlock(jade,{scale:'close'})));
  assert.equal(panelSeed({cast:['jade','mark'],prompt:'Close-up of Jade.',camera:'Close-up'},[jade,mark]), characterSeed('jade'));
  assert.equal(panelSeed({cast:['jade','mark'],prompt:'Jade and Mark walk.',camera:'Wide establishing shot'},[jade,mark]), characterSeed('jade|mark'));
  const negative=panelNegative([jade,mark]);
  assert.match(negative, /brown hair/);
  assert.match(negative, /blonde hair/);
  assert.match(negative, /clean-shaven/);
  assert.match(negative, /inconsistent face/);
  assert.match(negative, /different eye color/);
  assert.doesNotMatch(negative, /neck tattoo/);
  assert.equal(mockLookSheet().eyeColor, 'hazel-green');
  const app=fs.readFileSync(new URL('../app.js', import.meta.url),'utf8');
  assert.equal(app.split('describeLook(').length-1, 1);
  assert.match(app, /describe-reference/);
  assert.match(app, /preview-character/);
  assert.doesNotMatch(app, /describeFromReference\(\)[\s\S]*describeFromReference\(\)/);
});
